"""Freeze train/val/test scene splits before any tuning (PROJECT_GUIDELINES §6.3).

Samples scenes from an AlpaSim test suite with a fixed seed. Scenes already
used during development are forced into the training split.

Usage: python scripts/make_splits.py <alpasim-dir> <out.yaml>
"""

from __future__ import annotations

import argparse
import csv
import random
from pathlib import Path

import yaml

SUITE = "public_2604"
SEED = 0
SIZES = {"train": 16, "val": 4, "test": 4}
# Training scenes added after the first SFT round showed 16 scenes were too few.
# They come after the val/test positions of the seeded shuffle, so val and test
# are unchanged.
TRAIN_EXTRA = 48
# Closed-loop evaluation splits, frozen before any closed-loop tuning: 4 scenes
# could not separate policies (scene-level bootstrap CIs spanned [0, 0.75]).
CLOSED_LOOP = {"val_cl": 16, "test_cl": 16}
DEVELOPMENT_SCENES = ["clipgt-01d503d4-449b-46fc-8d78-9085e70d3554"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("alpasim_dir", type=Path)
    parser.add_argument("out", type=Path)
    args = parser.parse_args()

    scenes_dir = args.alpasim_dir / "data/scenes"
    with open(scenes_dir / "sim_suites.csv") as f:
        suite = {r["scene_id"]: r["uuid"] for r in csv.DictReader(f) if r["test_suite_id"] == SUITE}
    with open(scenes_dir / "sim_scenes.csv") as f:
        artifacts = {r["uuid"]: r for r in csv.DictReader(f)}

    pool = sorted(s for s in suite if s not in DEVELOPMENT_SCENES)
    random.Random(SEED).shuffle(pool)
    n_train = SIZES["train"] - len(DEVELOPMENT_SCENES)
    end_test = n_train + SIZES["val"] + SIZES["test"]
    chosen = {
        "train": DEVELOPMENT_SCENES + pool[:n_train] + pool[end_test : end_test + TRAIN_EXTRA],
        "val": pool[n_train : n_train + SIZES["val"]],
        "test": pool[n_train + SIZES["val"] : end_test],
    }
    start = end_test + TRAIN_EXTRA
    for name, size in CLOSED_LOOP.items():
        chosen[name] = pool[start : start + size]
        start += size
    splits = {
        name: [
            {
                "scene_id": s,
                "uuid": suite[s],
                "hf_path": artifacts[suite[s]]["path"],
                "hf_revision": artifacts[suite[s]]["hf_revision"],
            }
            for s in ids
        ]
        for name, ids in chosen.items()
    }
    header = (
        f"# Frozen scene splits: suite {SUITE}, seed {SEED}. Generated by scripts/make_splits.py;\n"
        "# do not edit by hand. Test scenes are for final evaluation only.\n"
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header + yaml.safe_dump(splits, sort_keys=False))
    print({k: len(v) for k, v in splits.items()})


if __name__ == "__main__":
    main()
